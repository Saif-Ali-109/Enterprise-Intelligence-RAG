#: The publisher page this test crawls. One page, depth 0 — the smallest corpus
#: that can still produce a multi-unit answer, so the test's cost is one request
#: to Atlassian and a handful of embeddings. A page no earlier verification used,
#: so the document is new and its vectors are written rather than reported
#: unchanged: an unchanged page indexes nothing, and a corpus of nothing answers
#: nothing.
START_URL = "https://developer.atlassian.com/cloud/jira/platform/rest/v3/api-group-issues/"

#: The name this test registers its source under, and the handle its own cleanup
#: and re-runs find it by.
SOURCE_NAME = "T076 e2e corpus"

#: Answerable from the page above, in the page's own terms. A question the
#: corpus cannot support is not a harder test of citations; it is a refusal, and
#: a refusal has no claims to check.
QUESTION = "How do you create an issue with the Jira Cloud platform REST API?"

NAMESPACE = "e2e-t076"

CRAWL_TIMEOUT_SECONDS = 300


