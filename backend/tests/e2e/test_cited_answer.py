"""T076 — one question against a real corpus, every claim cited (FR-002, SC-018).

This is the only test in the repository that checks the whole claim at once, and
so the only one that can catch a mistake that is invisible at every other seam:
that a fluent, plausible, unsourced answer is reachable. Everything the claim
rests on here is real, because a citation test over a corpus this file wrote
itself proves only that the test agrees with itself.

**Real:** the publisher page is fetched by the real crawler through the real
`POST /sources` endpoint; the chunks are embedded by the real model into a real
index; the answer is generated and verified by the real LLM provider; each
citation is checked against the registry rows this crawl wrote; and each link is
opened by a real HTTP request. The one thing the test does *not* do is assert
anything about the publisher's prose — the corpus is Atlassian's, not ours.

**Isolation.** Vectors go into a dedicated Pinecone namespace (`e2e-t076`) so a
failed run cannot contaminate the `atlassian-public` corpus, and the registry
rows are deleted on the way out rather than truncated, because truncation is
what wipes an operator's live registry. The test refuses to truncate: the whole
point of it is a corpus that other work also depends on.

**Gating.** Three dependencies are required and each missing one skips with an
explicit message rather than a bare `skip`: a live `GROQ_API_KEY` (generation),
a live `PINECONE_API_KEY` (embedding and search), and a reachable PostgreSQL
(`tests/fixtures/database.py` skips with the driver's own refusal text).

**What "every claim is cited" means here.** The response carries citations as a
list, not as inline markers, so the per-claim invariant is checked the way it
actually bites: each citation must (a) name a unit this crawl actually wrote,
(b) carry the registry's own URL for that document, and (c) carry a quote that
is found in the text that was embedded for that unit. A model that invents a
quote fails (c), and a model that cites a URL the registry does not vouch for
fails (b).
"""

